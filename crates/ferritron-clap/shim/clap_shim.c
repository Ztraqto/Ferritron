static bool render_has_hard_realtime_requirement(const clap_plugin_t* plugin) {
    (void)plugin;
    return false;
}

/* Offline rendering takes effect at activate: ask the host to reactivate. */
static bool render_set(const clap_plugin_t* plugin, clap_plugin_render_mode mode) {
    instance_t* instance = (instance_t*)plugin->plugin_data;
    bool offline = mode == CLAP_RENDER_OFFLINE;
    if (offline == instance->offline)
        return true;
    instance->offline = offline;
    const ferritron_render_api* ext = (const ferritron_render_api*)g_api->get_extension(FERRITRON_EXT_RENDER);
    if (ext)
        ext->set_offline(instance->core, offline);
    if (instance->active)
        instance->host->request_restart(instance->host);
    return true;
}

static const clap_plugin_render_t g_render = {render_has_hard_realtime_requirement, render_set};

