static int g_init_count;

static bool entry_init(const char* plugin_path) {
    (void)plugin_path;
    if (g_init_count++ > 0)
        return true;
    g_api = ferritron_clap_plugin_api();
    if (!g_api || g_api->abi_version != FERRITRON_ABI_VERSION || g_api->struct_size < sizeof(ferritron_plugin_api) ||
        !build_descriptor()) {
        g_init_count = 0;
        return false;
    }
    return true;
}

static void entry_deinit(void) {
    if (g_init_count > 0 && --g_init_count == 0)
        free_descriptor();
}

static const void* entry_get_factory(const char* factory_id) {
    if (g_init_count <= 0)
        return NULL;
#ifdef FERRITRON_HAVE_ARA
    if (ara_api() && (strcmp(factory_id, CLAP_EXT_ARA_FACTORY) == 0 || strcmp(factory_id, CLAP_EXT_ARA_FACTORY_COMPAT) == 0))
        return &g_ara_factory;
#endif
    return strcmp(factory_id, CLAP_PLUGIN_FACTORY_ID) == 0 ? &g_factory : NULL;
}

