/* Applies incoming parameter events. Sample-accurate automation comes later. */
static void apply_events(void* core, const clap_input_events_t* events) {
    if (!events)
        return;
    uint32_t count = events->size(events);
    for (uint32_t i = 0; i < count; ++i) {
        const clap_event_header_t* header = events->get(events, i);
        if (header->space_id != CLAP_CORE_EVENT_SPACE_ID || header->type != CLAP_EVENT_PARAM_VALUE)
            continue;
        const clap_event_param_value_t* ev = (const clap_event_param_value_t*)header;
        g_api->set_param(core, ev->param_id, g_api->to_normalized(ev->param_id, ev->value));
    }
}

static clap_process_status plugin_process(const clap_plugin_t* plugin, const clap_process_t* process) {
    void* core = core_of(plugin);

    /* CLAP delivers events sorted by time; keep parameter changes and notes, without allocating. */
    ferritron_event events[MAX_EVENTS];
    uint32_t num_events = 0;
    const bool notes = is_instrument();
    const clap_input_events_t* in_events = process->in_events;
    for (uint32_t i = 0, n = in_events ? in_events->size(in_events) : 0; i < n; ++i) {
        const clap_event_header_t* header = in_events->get(in_events, i);
        if (header->space_id != CLAP_CORE_EVENT_SPACE_ID)
            continue;
        ferritron_event ev;
        memset(&ev, 0, sizeof(ev));
        ev.offset = header->time;
        if (header->type == CLAP_EVENT_PARAM_VALUE) {
            const clap_event_param_value_t* p = (const clap_event_param_value_t*)header;
            ev.type = FERRITRON_EVENT_PARAM;
            ev.data.param.id = p->param_id;
            ev.data.param.normalized = g_api->to_normalized(p->param_id, p->value);
            if (num_events == MAX_EVENTS) {
                g_api->set_param(core, ev.data.param.id, ev.data.param.normalized); /* overflow: apply now */
                continue;
            }
        } else if (notes && (header->type == CLAP_EVENT_NOTE_ON || header->type == CLAP_EVENT_NOTE_OFF)) {
            const clap_event_note_t* note = (const clap_event_note_t*)header;
            ev.type = header->type == CLAP_EVENT_NOTE_ON ? FERRITRON_EVENT_NOTE_ON : FERRITRON_EVENT_NOTE_OFF;
            ev.data.note.note_id = note->note_id;
            ev.data.note.channel = note->channel < 0 ? 0 : note->channel;
            ev.data.note.key = note->key;
            ev.data.note.velocity = (float)note->velocity;
        } else if (notes && header->type == CLAP_EVENT_MIDI) {
            const clap_event_midi_t* midi = (const clap_event_midi_t*)header;
            uint8_t status = midi->data[0] & 0xF0;
            if (status != 0x90 && status != 0x80)
                continue;
            /* Note on with velocity 0 is a note off. */
            ev.type = status == 0x90 && midi->data[2] > 0 ? FERRITRON_EVENT_NOTE_ON : FERRITRON_EVENT_NOTE_OFF;
            ev.data.note.note_id = -1;
            ev.data.note.channel = midi->data[0] & 0x0F;
            ev.data.note.key = midi->data[1] & 0x7F;
            ev.data.note.velocity = (float)(midi->data[2] & 0x7F) / 127.0f;
        } else {
            continue;
        }
        if (num_events < MAX_EVENTS)
            events[num_events++] = ev;
    }

    if (process->audio_outputs_count < 1 || !process->audio_outputs[0].data32) {
        for (uint32_t i = 0; i < num_events; ++i)
            if (events[i].type == FERRITRON_EVENT_PARAM)
                g_api->set_param(core, events[i].data.param.id, events[i].data.param.normalized);
        return CLAP_PROCESS_CONTINUE;
    }
    clap_audio_buffer_t* out = &process->audio_outputs[0];
    const clap_audio_buffer_t* in = process->audio_inputs_count > 0 ? &process->audio_inputs[0] : NULL;
    uint32_t channels = out->channel_count < CHANNELS ? out->channel_count : CHANNELS;
    size_t bytes = (size_t)process->frames_count * sizeof(float);

    /* Copy inputs to outputs so the plugin processes in place. */
    float* ptrs[CHANNELS] = {NULL, NULL};
    for (uint32_t ch = 0; ch < channels; ++ch) {
        float* dst = out->data32[ch];
        const float* src = in && in->data32 && ch < in->channel_count ? in->data32[ch] : NULL;
        if (!src)
            memset(dst, 0, bytes);
        else if (src != dst)
            memmove(dst, src, bytes);
        ptrs[ch] = dst;
    }
    instance_t* self = (instance_t*)plugin->plugin_data;
    /* An ARA playback renderer plays its regions at the song position; the plugin processes the result. */
    const ferritron_ara_api* ara = ara_api();
    if (ara) {
        const clap_event_transport_t* t = process->transport;
        int64_t position = 0;
        if (t && (t->flags & CLAP_TRANSPORT_HAS_SECONDS_TIMELINE))
            position = (int64_t)llround((double)t->song_pos_seconds / (double)CLAP_SECTIME_FACTOR * self->sample_rate);
        bool playing = t && (t->flags & CLAP_TRANSPORT_IS_PLAYING);
        ara->render(core, ptrs, channels, process->frames_count, position, playing);
    }
    ferritron_executor executor = {self, pool_run};
    bool silent = false;
    if (!g_api->process(core, ptrs, channels, process->frames_count, events, num_events,
                        self->host_pool ? &executor : NULL)) {
        for (uint32_t ch = 0; ch < channels; ++ch)
            memset(ptrs[ch], 0, bytes);
    } else {
        const ferritron_sleep_api* sleep = self->sleep;
        silent = sleep && sleep->silent(core);
    }
    /* A sleeping plugin outputs silence: the host may stop calling until input or events arrive. */
    out->constant_mask = silent ? (((uint64_t)1 << channels) - 1) : 0;
    report_edits((instance_t*)plugin->plugin_data, process->out_events);
    return silent ? CLAP_PROCESS_SLEEP : CLAP_PROCESS_CONTINUE;
}

/* --- Extensions ---------------------------------------------------------- */

/* Effects: stereo in and out. Instruments: stereo out only. */
static uint32_t ports_count(const clap_plugin_t* plugin, bool is_input) {
    (void)plugin;
    return is_input && is_instrument() ? 0 : 1;
}

static bool ports_get(const clap_plugin_t* plugin, uint32_t index, bool is_input, clap_audio_port_info_t* info) {
    if (index >= ports_count(plugin, is_input))
        return false;
    const char* name = is_input ? "Input" : "Output";
    info->id = 0;
    copy_utf8(info->name, sizeof(info->name), name, strlen(name));
    info->flags = CLAP_AUDIO_PORT_IS_MAIN;
    const instance_t* instance = (const instance_t*)plugin->plugin_data;
    info->channel_count = instance->channels;
    info->port_type = instance->channels == 1 ? CLAP_PORT_MONO : CLAP_PORT_STEREO;
    info->in_place_pair = is_instrument() ? CLAP_INVALID_ID : 0; /* input 0 and output 0 may share buffers */
    return true;
}

static const clap_plugin_audio_ports_t g_audio_ports = {ports_count, ports_get};

/* Port configurations: 0 = stereo (default), 1 = mono. */
static uint32_t ports_config_count(const clap_plugin_t* plugin) {
    (void)plugin;
    return 2;
}

static bool ports_config_get(const clap_plugin_t* plugin, uint32_t index, clap_audio_ports_config_t* config) {
    (void)plugin;
    if (index > 1)
        return false;
    uint32_t channels = index == 0 ? 2 : 1;
    const char* name = index == 0 ? "Stereo" : "Mono";
    config->id = index;
    copy_utf8(config->name, sizeof(config->name), name, strlen(name));
    config->input_port_count = is_instrument() ? 0 : 1;
    config->output_port_count = 1;
    config->has_main_input = !is_instrument();
    config->main_input_channel_count = is_instrument() ? 0 : channels;
    config->main_input_port_type = is_instrument() ? NULL : index == 0 ? CLAP_PORT_STEREO : CLAP_PORT_MONO;
    config->has_main_output = true;
    config->main_output_channel_count = channels;
    config->main_output_port_type = index == 0 ? CLAP_PORT_STEREO : CLAP_PORT_MONO;
    return true;
}

/* Hosts select a configuration while the plugin is inactive. */
static bool ports_config_select(const clap_plugin_t* plugin, clap_id config_id) {
    instance_t* instance = (instance_t*)plugin->plugin_data;
    if (config_id > 1 || instance->active)
        return false;
    instance->channels = config_id == 0 ? 2 : 1;
    return true;
}

static const clap_plugin_audio_ports_config_t g_audio_ports_config = {ports_config_count, ports_config_get, ports_config_select};

static uint32_t note_ports_count(const clap_plugin_t* plugin, bool is_input) {
    (void)plugin;
    return is_input && is_instrument() ? 1 : 0;
}

static bool note_ports_get(const clap_plugin_t* plugin, uint32_t index, bool is_input, clap_note_port_info_t* info) {
    if (index >= note_ports_count(plugin, is_input))
        return false;
    info->id = 0;
    info->supported_dialects = CLAP_NOTE_DIALECT_CLAP | CLAP_NOTE_DIALECT_MIDI;
    info->preferred_dialect = CLAP_NOTE_DIALECT_CLAP;
    copy_utf8(info->name, sizeof(info->name), "Notes", 5);
    return true;
}

static const clap_plugin_note_ports_t g_note_ports = {note_ports_count, note_ports_get};

static uint32_t params_count(const clap_plugin_t* plugin) {
    (void)plugin;
    return g_api->param_count();
}

static bool params_get_info(const clap_plugin_t* plugin, uint32_t index, clap_param_info_t* out) {
    (void)plugin;
    ferritron_param_info info;
    if (!g_api->param_info(index, &info))
        return false;
    memset(out, 0, sizeof(*out));
    out->id = info.id;
    out->flags = (info.flags & FERRITRON_PARAM_NOT_AUTOMATABLE) ? 0 : CLAP_PARAM_IS_AUTOMATABLE;
    if (info.step_count > 0)
        out->flags |= CLAP_PARAM_IS_STEPPED;
    if (info.flags & FERRITRON_PARAM_LIST)
        out->flags |= CLAP_PARAM_IS_ENUM;
    if (info.flags & FERRITRON_PARAM_BYPASS)
        out->flags |= CLAP_PARAM_IS_BYPASS;
    if (info.flags & FERRITRON_PARAM_HIDDEN)
        out->flags |= CLAP_PARAM_IS_HIDDEN;
    out->cookie = NULL;
    copy_utf8(out->name, sizeof(out->name), info.name.ptr ? info.name.ptr : "", info.name.len);
    out->module[0] = 0;
    /* CLAP works with plain values; the ABI with normalized ones. */
    out->min_value = g_api->to_plain(info.id, 0.0);
    out->max_value = g_api->to_plain(info.id, 1.0);
    out->default_value = g_api->to_plain(info.id, info.default_normalized);
    return true;
}

static bool params_get_value(const clap_plugin_t* plugin, clap_id id, double* value) {
    uint32_t count = g_api->param_count();
    for (uint32_t i = 0; i < count; ++i) {
        ferritron_param_info info;
        if (g_api->param_info(i, &info) && info.id == id) {
            *value = g_api->to_plain(id, g_api->get_param(core_of(plugin), id));
            return true;
        }
    }
    return false;
}

static bool params_value_to_text(const clap_plugin_t* plugin, clap_id id, double value, char* buf, uint32_t cap) {
    (void)plugin;
    if (cap == 0)
        return false;
    char text[256];
    int32_t len = g_api->format_param(id, g_api->to_normalized(id, value), text, sizeof(text));
    if (len < 0)
        return false;
    copy_utf8(buf, cap, text, (size_t)len);
    return true;
}

static bool params_text_to_value(const clap_plugin_t* plugin, clap_id id, const char* text, double* value) {
    (void)plugin;
    ferritron_str s = {text, (uint32_t)strlen(text)};
    double normalized;
    if (!g_api->parse_param(id, s, &normalized))
        return false;
    *value = g_api->to_plain(id, normalized);
    return true;
}

static void params_flush(const clap_plugin_t* plugin, const clap_input_events_t* in, const clap_output_events_t* out) {
    apply_events(core_of(plugin), in);
    report_edits((instance_t*)plugin->plugin_data, out);
}

