static const char* const g_effect_features[] = {CLAP_PLUGIN_FEATURE_AUDIO_EFFECT, CLAP_PLUGIN_FEATURE_STEREO, NULL};
static const char* const g_instrument_features[] = {CLAP_PLUGIN_FEATURE_INSTRUMENT, CLAP_PLUGIN_FEATURE_SYNTHESIZER,
                                                    CLAP_PLUGIN_FEATURE_STEREO, NULL};

static bool is_instrument(void) {
    return g_api->info->kind == FERRITRON_PLUGIN_INSTRUMENT;
}

/* ARA 2 (ferritron.ara.v1), when the plugin has it and the shim was built with the ARA SDK. */
static const ferritron_ara_api* ara_api(void) {
#ifdef FERRITRON_HAVE_ARA
    return (const ferritron_ara_api*)g_api->get_extension(FERRITRON_EXT_ARA);
#else
    return NULL;
#endif
}

#ifdef FERRITRON_HAVE_ARA
static const char* const g_ara_effect_features[] = {CLAP_PLUGIN_FEATURE_AUDIO_EFFECT, CLAP_PLUGIN_FEATURE_STEREO,
                                                    CLAP_PLUGIN_FEATURE_ARA_SUPPORTED, NULL};
static const char* const g_ara_instrument_features[] = {CLAP_PLUGIN_FEATURE_INSTRUMENT, CLAP_PLUGIN_FEATURE_SYNTHESIZER,
                                                        CLAP_PLUGIN_FEATURE_STEREO, CLAP_PLUGIN_FEATURE_ARA_SUPPORTED, NULL};
#endif
static clap_plugin_descriptor_t g_descriptor;

static void free_descriptor(void) {
    free((void*)g_descriptor.id);
    free((void*)g_descriptor.name);
    free((void*)g_descriptor.vendor);
    free((void*)g_descriptor.url);
    free((void*)g_descriptor.version);
    memset(&g_descriptor, 0, sizeof(g_descriptor));
}

static bool build_descriptor(void) {
    const ferritron_plugin_info* info = g_api->info;
    g_descriptor.clap_version = (clap_version_t)CLAP_VERSION_INIT;
    g_descriptor.id = dup_str(info->id);
    g_descriptor.name = dup_str(info->name);
    g_descriptor.vendor = dup_str(info->vendor);
    g_descriptor.url = dup_str(info->url);
    g_descriptor.manual_url = "";
    g_descriptor.support_url = "";
    g_descriptor.version = dup_str(info->version);
    g_descriptor.description = "";
    g_descriptor.features = is_instrument() ? g_instrument_features : g_effect_features;
#ifdef FERRITRON_HAVE_ARA
    if (ara_api())
        g_descriptor.features = is_instrument() ? g_ara_instrument_features : g_ara_effect_features;
#endif
    if (!g_descriptor.id || !g_descriptor.name || !g_descriptor.vendor || !g_descriptor.url || !g_descriptor.version) {
        free_descriptor();
        return false;
    }
    return true;
}

/* --- Plugin instance ----------------------------------------------------- */

enum { EDIT_BEGIN, EDIT_VALUE, EDIT_END };

typedef struct {
    uint32_t kind;
    uint32_t id;
    double normalized;
} edit_t;

typedef struct {
    clap_plugin_t plugin;
    const clap_host_t* host;
    const clap_host_params_t* host_params; /* may be NULL */
    const clap_host_track_info_t* host_track_info; /* may be NULL */
    void* core;
    bool active;
    bool offline; /* the host's render mode (CLAP_EXT_RENDER) */
    const ferritron_sleep_api* sleep; /* silence (FERRITRON_EXT_SLEEP); may be NULL */
    double sample_rate;
    uint32_t channels; /* per port: 2, or 1 after the host selected the mono configuration */

    /* Editor (ferritron.view.v1), if the plugin has one. Sizes reported to the
       host are physical: logical size times the scale (host's, or window DPI). */
    const ferritron_view_api* view_api;
    ferritron_view_host view_host;
    void* view;
    void* parent;
    uint32_t editor_width; /* logical; kept so a reopened editor keeps its size */
    uint32_t editor_height;
    const ferritron_editor_size_api* editor_size; /* saves the size with the state; may be NULL */
    double host_scale; /* 0: not given by the host */

    /* The host's thread pool, if it has one: ctx.parallel_for uses it. */
    const clap_host_thread_pool_t* host_pool;
    void (*pool_task)(void* data, uint32_t index);
    void* pool_data;

    /* Edits from the editor, reported to the host as output events in the
       next process or flush call. Guarded by a spinlock held only for copies. */
    edit_t edits[MAX_EDITS];
    uint32_t num_edits;
    long edits_lock;
} instance_t;

static void* core_of(const clap_plugin_t* plugin) {
    return ((const instance_t*)plugin->plugin_data)->core;
}

/* --- host link (ferritron.host.v1): track name, edits made by the plugin -- */

static void update_track_name(const clap_plugin_t* plugin);

static bool plugin_init(const clap_plugin_t* plugin) {
    instance_t* instance = (instance_t*)plugin->plugin_data;
    instance->host_params = (const clap_host_params_t*)instance->host->get_extension(instance->host, CLAP_EXT_PARAMS);
    instance->host_pool = (const clap_host_thread_pool_t*)instance->host->get_extension(instance->host, CLAP_EXT_THREAD_POOL);
    instance->host_track_info = (const clap_host_track_info_t*)instance->host->get_extension(instance->host, CLAP_EXT_TRACK_INFO);
    update_track_name(plugin);
    return true;
}

/* ferritron_executor on top of the host's thread pool (called from process). */
static bool pool_run(void* ctx, uint32_t count, void (*task)(void*, uint32_t), void* data) {
    instance_t* instance = (instance_t*)ctx;
    instance->pool_task = task;
    instance->pool_data = data;
    bool ok = instance->host_pool->request_exec(instance->host, count);
    instance->pool_task = NULL;
    return ok;
}

/* clap_plugin_thread_pool.exec: the host runs one task on its worker. */
static void pool_exec(const clap_plugin_t* plugin, uint32_t task_index) {
    instance_t* instance = (instance_t*)plugin->plugin_data;
    if (instance->pool_task)
        instance->pool_task(instance->pool_data, task_index);
}

static const clap_plugin_thread_pool_t g_thread_pool = {pool_exec};

static void gui_close(instance_t* instance) {
    if (instance->view)
        instance->view_api->close(instance->view);
    instance->view = NULL;
    instance->parent = NULL;
}

static void plugin_destroy(const clap_plugin_t* plugin) {
    instance_t* instance = (instance_t*)plugin->plugin_data;
    gui_close(instance);
    g_api->destroy(instance->core);
    free(instance);
}

/* Moves queued editor edits into the host's output event list. */
static void report_edits(instance_t* instance, const clap_output_events_t* out) {
    edit_t edits[MAX_EDITS];
    SPIN_LOCK(&instance->edits_lock);
    uint32_t count = instance->num_edits;
    memcpy(edits, instance->edits, count * sizeof(edit_t));
    instance->num_edits = 0;
    SPIN_UNLOCK(&instance->edits_lock);
    if (!out)
        return;
    for (uint32_t i = 0; i < count; ++i) {
        const edit_t* e = &edits[i];
        if (e->kind == EDIT_VALUE) {
            clap_event_param_value_t ev;
            memset(&ev, 0, sizeof(ev));
            ev.header.size = sizeof(ev);
            ev.header.space_id = CLAP_CORE_EVENT_SPACE_ID;
            ev.header.type = CLAP_EVENT_PARAM_VALUE;
            ev.param_id = e->id;
            ev.note_id = -1;
            ev.port_index = -1;
            ev.channel = -1;
            ev.key = -1;
            ev.value = g_api->to_plain(e->id, e->normalized);
            out->try_push(out, &ev.header);
        } else {
            clap_event_param_gesture_t ev;
            memset(&ev, 0, sizeof(ev));
            ev.header.size = sizeof(ev);
            ev.header.space_id = CLAP_CORE_EVENT_SPACE_ID;
            ev.header.type = e->kind == EDIT_BEGIN ? CLAP_EVENT_PARAM_GESTURE_BEGIN : CLAP_EVENT_PARAM_GESTURE_END;
            ev.param_id = e->id;
            out->try_push(out, &ev.header);
        }
    }
}

static bool plugin_activate(const clap_plugin_t* plugin, double sample_rate, uint32_t min_frames, uint32_t max_frames) {
    (void)min_frames;
    g_api->activate(core_of(plugin), sample_rate, max_frames);
    instance_t* instance = (instance_t*)plugin->plugin_data;
    instance->active = true;
    instance->sample_rate = sample_rate;
    const ferritron_ara_api* ara = ara_api();
    if (ara)
        ara->set_rendering(instance->core, true, sample_rate, instance->channels, max_frames);
    return true; /* a failed plugin outputs silence instead of failing the host */
}

static void plugin_deactivate(const clap_plugin_t* plugin) {
    instance_t* instance = (instance_t*)plugin->plugin_data;
    instance->active = false;
    const ferritron_ara_api* ara = ara_api();
    if (ara)
        ara->set_rendering(instance->core, false, 0, 0, 0);
}

