/* --- Strings ------------------------------------------------------------- */

static char* dup_str(ferritron_str s) {
    char* out = (char*)malloc((size_t)s.len + 1);
    if (!out)
        return NULL;
    if (s.len)
        memcpy(out, s.ptr, s.len);
    out[s.len] = 0;
    return out;
}

/* Copies UTF-8 into a fixed buffer without splitting a character. */
static void copy_utf8(char* dst, size_t cap, const char* src, size_t len) {
    if (len > cap - 1) {
        len = cap - 1;
        /* Only when truncating: back up to the start of the cut character. */
        while (len > 0 && ((unsigned char)src[len] & 0xC0) == 0x80)
            --len;
    }
    memcpy(dst, src, len);
    dst[len] = 0;
}

