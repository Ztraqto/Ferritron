/* macOS ("cocoa") sizes are points; the view renders at the backing scale itself. */
static double gui_scale(const instance_t* instance) {
#ifdef __APPLE__
    (void)instance;
    return 1.0;
#endif
    if (instance->host_scale > 0)
        return instance->host_scale;
#ifdef _WIN32
    UINT dpi = instance->parent ? GetDpiForWindow((HWND)instance->parent) : GetDpiForSystem();
    return dpi ? dpi / 96.0 : 1.0;
#else
    return 1.0;
#endif
}

static uint32_t to_physical(uint32_t logical, double scale) {
    return (uint32_t)lround(logical * scale);
}

static uint32_t clamp_u32(uint32_t v, uint32_t lo, uint32_t hi) {
    return v < lo ? lo : v > hi ? hi : v;
}

static bool gui_resizable(const instance_t* instance) {
    const ferritron_view_api* api = instance->view_api;
    return api && (api->min_width != api->max_width || api->min_height != api->max_height);
}

static void gui_apply_size(instance_t* instance) {
    if (instance->view) {
        double s = gui_scale(instance);
        instance->view_api->set_size(instance->view, to_physical(instance->editor_width, s),
                                     to_physical(instance->editor_height, s), s);
    }
}

static bool gui_is_api_supported(const clap_plugin_t* plugin, const char* api, bool is_floating) {
#ifdef _WIN32
    return gui_instance(plugin)->view_api && !is_floating && strcmp(api, CLAP_WINDOW_API_WIN32) == 0;
#elif defined(__APPLE__)
    return gui_instance(plugin)->view_api && !is_floating && strcmp(api, CLAP_WINDOW_API_COCOA) == 0;
#else
    (void)plugin;
    (void)api;
    (void)is_floating;
    return false;
#endif
}

static bool gui_get_preferred_api(const clap_plugin_t* plugin, const char** api, bool* is_floating) {
    (void)plugin;
#ifdef __APPLE__
    *api = CLAP_WINDOW_API_COCOA;
#else
    *api = CLAP_WINDOW_API_WIN32;
#endif
    *is_floating = false;
    return true;
}

static bool gui_create(const clap_plugin_t* plugin, const char* api, bool is_floating) {
    return gui_is_api_supported(plugin, api, is_floating); /* the view opens in set_parent */
}

static void gui_destroy(const clap_plugin_t* plugin) {
    gui_close(gui_instance(plugin));
}

static bool gui_set_scale(const clap_plugin_t* plugin, double scale) {
    instance_t* instance = gui_instance(plugin);
    if (!(scale > 0))
        return false;
    instance->host_scale = scale;
    gui_apply_size(instance);
    return true;
}

static bool gui_get_size(const clap_plugin_t* plugin, uint32_t* width, uint32_t* height) {
    const instance_t* instance = gui_instance(plugin);
    if (!instance->view_api)
        return false;
    double s = gui_scale(instance);
    *width = to_physical(instance->editor_width, s);
    *height = to_physical(instance->editor_height, s);
    return true;
}

static bool gui_can_resize(const clap_plugin_t* plugin) {
    return gui_resizable(gui_instance(plugin));
}

static bool gui_get_resize_hints(const clap_plugin_t* plugin, clap_gui_resize_hints_t* hints) {
    const instance_t* instance = gui_instance(plugin);
    if (!gui_resizable(instance))
        return false;
    hints->can_resize_horizontally = instance->view_api->min_width != instance->view_api->max_width;
    hints->can_resize_vertically = instance->view_api->min_height != instance->view_api->max_height;
    hints->preserve_aspect_ratio = false;
    hints->aspect_ratio_width = 0;
    hints->aspect_ratio_height = 0;
    return true;
}

static bool gui_adjust_size(const clap_plugin_t* plugin, uint32_t* width, uint32_t* height) {
    const instance_t* instance = gui_instance(plugin);
    const ferritron_view_api* api = instance->view_api;
    if (!api)
        return false;
    double s = gui_scale(instance);
    *width = clamp_u32(*width, to_physical(api->min_width, s), to_physical(api->max_width, s));
    *height = clamp_u32(*height, to_physical(api->min_height, s), to_physical(api->max_height, s));
    return true;
}

static bool gui_set_size(const clap_plugin_t* plugin, uint32_t width, uint32_t height) {
    instance_t* instance = gui_instance(plugin);
    uint32_t w = width, h = height;
    if (!gui_adjust_size(plugin, &w, &h) || w != width || h != height)
        return false;
    double s = gui_scale(instance);
    instance->editor_width = (uint32_t)lround(width / s);
    instance->editor_height = (uint32_t)lround(height / s);
    if (instance->editor_size)
        instance->editor_size->set(instance->core, instance->editor_width, instance->editor_height);
    gui_apply_size(instance);
    return true;
}

/* After loading state: the editor takes the size saved with it. */
static void gui_restore_size(instance_t* instance) {
    const ferritron_view_api* api = instance->view_api;
    uint32_t w, h;
    if (!api || !instance->editor_size || !instance->editor_size->get(instance->core, &w, &h))
        return;
    w = clamp_u32(w, api->min_width, api->max_width);
    h = clamp_u32(h, api->min_height, api->max_height);
    if (w == instance->editor_width && h == instance->editor_height)
        return;
    instance->editor_width = w;
    instance->editor_height = h;
    if (instance->view) {
        const clap_host_gui_t* gui = (const clap_host_gui_t*)instance->host->get_extension(instance->host, CLAP_EXT_GUI);
        double s = gui_scale(instance);
        if (gui && gui->request_resize)
            gui->request_resize(instance->host, to_physical(w, s), to_physical(h, s));
        gui_apply_size(instance);
    }
}

static bool gui_set_parent(const clap_plugin_t* plugin, const clap_window_t* window) {
    instance_t* instance = gui_instance(plugin);
    if (!instance->view_api || !window)
        return false;
    gui_close(instance);
    instance->parent = window->ptr; /* HWND or NSView* */
    double s = gui_scale(instance);
    instance->view = instance->view_api->open(window->ptr, &instance->view_host,
                                              to_physical(instance->editor_width, s),
                                              to_physical(instance->editor_height, s), s);
    return instance->view != NULL;
}

