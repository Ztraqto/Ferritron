static const clap_plugin_t* factory_create(const clap_plugin_factory_t* factory, const clap_host_t* host,
                                           const char* plugin_id) {
    (void)factory;
    if (!host || !clap_version_is_compatible(host->clap_version) || strcmp(plugin_id, g_descriptor.id) != 0)
        return NULL;
    instance_t* instance = (instance_t*)calloc(1, sizeof(instance_t));
    if (!instance)
        return NULL;
    instance->host = host;
    instance->channels = CHANNELS;
    instance->view_api = (const ferritron_view_api*)g_api->get_extension(FERRITRON_EXT_VIEW);
    instance->sleep = sleep_api();
    instance->view_host.ctx = instance;
    instance->view_host.get_param = view_get;
    instance->view_host.begin_edit = view_begin;
    instance->view_host.perform_edit = view_perform;
    instance->view_host.end_edit = view_end;
    if (instance->view_api) {
        instance->editor_width = instance->view_api->width;
        instance->editor_height = instance->view_api->height;
        instance->editor_size = (const ferritron_editor_size_api*)g_api->get_extension(FERRITRON_EXT_EDITOR_SIZE);
    }
    instance->core = g_api->create();
    if (!instance->core) {
        free(instance);
        return NULL;
    }
    /* Edits the plugin makes by itself; ctx is the instance, as for the editor's view host. */
    const ferritron_host_api2* link2 = (const ferritron_host_api2*)g_api->get_extension(FERRITRON_EXT_HOST2);
    const ferritron_host_api* link = (const ferritron_host_api*)g_api->get_extension(FERRITRON_EXT_HOST);
    if (link2) {
        ferritron_host_callbacks2 callbacks = {instance, host_edit2, host_request_process};
        link2->attach(instance->core, &callbacks);
    } else if (link) {
        ferritron_host_callbacks callbacks = {instance, host_edited};
        link->attach(instance->core, &callbacks);
    }
    clap_plugin_t* p = &instance->plugin;
    p->desc = &g_descriptor;
    p->plugin_data = instance;
    p->init = plugin_init;
    p->destroy = plugin_destroy;
    p->activate = plugin_activate;
    p->deactivate = plugin_deactivate;
    p->start_processing = plugin_start_processing;
    p->stop_processing = plugin_stop_processing;
    p->reset = plugin_reset;
    p->process = plugin_process;
    p->get_extension = plugin_get_extension;
    p->on_main_thread = plugin_on_main_thread;
    return p;
}

